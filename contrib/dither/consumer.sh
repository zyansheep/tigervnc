#!/usr/bin/env bash
# Print the self-contained <NAME>.nix for a release: fetchFromGitHub of the tag with its fixed hash, and package.nix
# inlined, so a consumer copies one file and needs nothing else from this repository (no import from derivation).
# usage: consumer.sh <tag> <sri-hash>
set -euo pipefail
here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
# shellcheck source=dither.conf
source "$here/dither.conf"
tag=$1
hash=$2
nixpkgs_rev=$(grep -o 'archive/[0-9a-f]\{40\}' "$here/nixpkgs.nix" | cut -d/ -f2)

cat <<EOF
# $NAME from https://github.com/$FORK at $tag: upstream's ${tag%%-dither.*} with this fork's
# commits on top (https://github.com/$FORK/compare/${tag%%-dither.*}...$tag).
# Generated by contrib/dither/consumer.sh for the release; built and smoke-tested by the fork's CI against nixpkgs
# $nixpkgs_rev. Copy it as it is; a new release brings a new file.
#   nix-build $NAME.nix
{ pkgs ? import <nixpkgs> { } }:
let
  src = pkgs.fetchFromGitHub {
    owner = "${FORK%%/*}";
    repo = "${FORK##*/}";
    tag = "$tag";
    hash = "$hash";
  };
in
pkgs.callPackage (
EOF
sed 's/^/  /; s/^  $//' "$here/package.nix"
cat <<EOF
) {
  inherit src;
  version = "${tag#v}";
}
EOF
